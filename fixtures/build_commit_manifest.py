"""
Build a pre-commit review manifest from `git status`.

Classifies every dirty path into:
- ``commit``: new engine code, tests, fixtures, docs, packaging from the
  HYPER-BROWSER cycles (safe to stage after a normal diff read);
- ``review``: pre-existing tracked files modified before AND during the
  cycles (owner WIP is interleaved; read the diff file by file);
- ``never``: live-secret captures and root experiment scripts that must
  never be committed (several are already fenced by .gitignore).

Also secret-scans the commit/review candidates and checks that every
``never`` path is actually ignored by git. Writes
docs/engineering/COMMIT_REVIEW.md. Usage: python -m fixtures.build_commit_manifest
"""

from __future__ import annotations

import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

NEVER_PATTERNS = (
    re.compile(r"cookies.*\.json$", re.I),
    re.compile(r".*(localstorage|sessionstorage).*\.json$", re.I),
    re.compile(r".*_state\.json$", re.I),
    re.compile(r"^(analyze_cart|browse_paneer|checkout_generator|check_cookie|connect_live|cookie_utils|extract_real|inspect_|launch_live|proxy_utils|run_transfer|shop_|simulate_|survey_links|verify_checkout|web_api_cart)", re.I),
    re.compile(r"^cart_data_raw\.json$", re.I),
)

COMMIT_PREFIXES = ("agent_browser/", "fixtures/", "benchmarks/", "docs/", "tests/")
COMMIT_FILES = {"pyproject.toml", "requirements.txt", ".gitignore", "README.md"}

SECRET_PATTERNS = (
    ("bearer-token", re.compile(r"Bearer\s+[A-Za-z0-9._\-]{12,}")),
    ("session-cookie", re.compile(r"(?:session|sid|auth)[\"']?\s*[:=]\s*[\"'][A-Za-z0-9._\-]{12,}[\"']", re.I)),
    ("private-key", re.compile(r"BEGIN (?:RSA |EC )?PRIVATE KEY")),
    ("jwt", re.compile(r"eyJ[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}\.")),
)


def classify(path: str, status: str) -> str:
    p = path.replace("\\", "/")
    if any(rx.search(p) for rx in NEVER_PATTERNS):
        return "never"
    if p in COMMIT_FILES or p.startswith(COMMIT_PREFIXES) or p.startswith("test_"):
        return "commit" if status == "??" else "review"
    if status == "??":
        return "review"
    return "review"


def _git(*args) -> str:
    proc = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=30)
    return proc.stdout


def scan_secrets(paths):
    hits = []
    for path in paths:
        full = os.path.join(ROOT, path)
        if not os.path.isfile(full) or os.path.getsize(full) > 2_000_000:
            continue
        try:
            text = open(full, encoding="utf-8", errors="replace").read()
        except Exception:
            continue
        for name, rx in SECRET_PATTERNS:
            if rx.search(text):
                hits.append({"path": path, "pattern": name,
                             "test_data": path.startswith("test_")})
    return hits


def main() -> int:
    status_out = _git("status", "--porcelain")
    entries = []
    for line in status_out.splitlines():
        if not line.strip():
            continue
        status, path = line[:2], line[3:].strip().strip('"')
        entries.append((status, path, classify(path, status)))

    groups = {"commit": [], "review": [], "never": []}
    for status, path, group in entries:
        groups[group].append((status, path))

    ignored_check = {}
    for _, path in groups["never"]:
        out = _git("check-ignore", path)
        ignored_check[path] = bool(out.strip())

    hits = scan_secrets([p for _, p in groups["commit"] + groups["review"]])
    real_hits = [h for h in hits if not h["test_data"]]

    lines = ["# Commit review manifest", "",
             "Generated by `python -m fixtures.build_commit_manifest`. Nothing is staged by this tool.", ""]
    for group, title in (("commit", "Safe to stage (new cycle work)"),
                         ("review", "Review the diff file by file (owner WIP interleaved)"),
                         ("never", "NEVER commit")):
        lines.append(f"## {title} ({len(groups[group])})")
        lines.append("")
        for status, path in sorted(groups[group]):
            extra = ""
            if group == "never":
                extra = " -- ignored: " + ("yes" if ignored_check.get(path) else "NO (add to .gitignore or delete)")
            lines.append(f"- `{status}` `{path}`{extra}")
        lines.append("")
    lines.append("## Secret scan (commit + review candidates)")
    lines.append("")
    if real_hits:
        for h in real_hits:
            lines.append(f"- HIT `{h['pattern']}` in `{h['path']}` -- inspect before staging")
    else:
        lines.append("- No secret-pattern hits outside test fixtures (test files use fake values like 'topsecret').")
    lines.append("")
    unignored = [p for p, ok in ignored_check.items() if not ok]
    lines.append(f"Unignored never-commit paths: {len(unignored)} (root experiment scripts are code the owner may keep locally; they are listed, not auto-ignored).")

    out_path = os.path.join(ROOT, "docs", "engineering", "COMMIT_REVIEW.md")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"commit={len(groups['commit'])} review={len(groups['review'])} never={len(groups['never'])} "
          f"secret_hits={len(real_hits)} unignored_never={len(unignored)}")
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
